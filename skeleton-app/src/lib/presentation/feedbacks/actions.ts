/**
 * actions - 演出を出す「アクション」のカタログ＝演出ポイントの正本。
 *
 * 発火規律（何をここに入れ、いつ emitFeedback するか）:
 * - 確定／コミットの節目に出す＝操作がドメイン状態を変える瞬間の「何が起きた／確定した」の因果フィードバックに絞る
 * - ビュー／ナビ切替（タブ・ドロワー・スクロール・ホバー）は入れない＝見え方だけの変化には付けない
 * - 連続操作（スライダ等）は途中で出さず、確定（release／決定）時に 1 回だけ
 * - 強度は結果の重みに比例（重い／不可逆＝強め・軽い確定＝控えめ）。調整は各媒体側に持つ
 * - 本番でない文脈は決着系を抑制（例: 試運転 ignoreWinner＝勝敗演出なし）
 *
 * 各媒体（音・トースト・将来のアニメ等）はこの GameAction をキーに自分の表現へ写像する。
 * 新しい演出ポイントを足す = ここに 1 語足す（どの媒体が反応するかは各媒体が独立に決める）。
 * 再生中の move/turn/damage 等（フレーム差分由来の cue）は別カテゴリで、ここには含めない。
 */

export type GameAction =
  // 構築フェーズの確定操作
  | "build"
  | "deploy"
  | "pull"
  | "push"
  | "rename"
  | "delete"
  | "baseImage"
  | "allocate"
  | "revert"
  // 実行フェーズの開始操作
  | "run"
  // システム
  | "audioOn";
